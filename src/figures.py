def _save(fig, name: str) -> Path:
    DOC.mkdir(parents=True, exist_ok=True)
    RES.mkdir(parents=True, exist_ok=True)
    for d in (DOC, RES):
        fig.savefig(d / name, dpi=140, bbox_inches="tight")
    plt.close(fig)
    return DOC / name


def _ci_bars(ax, tags, metric, summary, color="#2c5aa0"):
    est = [summary["conditions"][t][metric]["est"] for t in tags]
    lo = [summary["conditions"][t][metric]["lo"] for t in tags]
    hi = [summary["conditions"][t][metric]["hi"] for t in tags]
    yerr = np.array([[e - l, h - e] for e, l, h in zip(est, lo, hi)]).T
    x = np.arange(len(tags))
    ax.bar(x, est, yerr=yerr, capsize=4, color=color, alpha=0.85, ecolor="#333", width=0.7)
    ax.set_xticks(x, [LABEL.get(t, t) for t in tags], fontsize=9)
    ax.set_ylabel(metric.replace("_", " "))
    return est


def conditions_vs_baseline(summary) -> Path:
    """Main grid: call_exact and mmlu with 95% CI vs fp/rtn baselines."""
    tags = [t for t in ("fp", "rtn", "awq_short", "awq_long_nomask", "awq_long_masked") if t in summary["conditions"]]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
    colors = ["#6b7280", "#9ca3af", "#3b82f6", "#10b981", "#ef4444"]
    for ax, metric, title in (
        (axes[0], "call_exact", "Tool-call exact match (primary)"),
        (axes[1], "mmlu_acc", "MMLU-lite (400 questions)"),
    ):
        est = [summary["conditions"][t][metric]["est"] for t in tags]
        lo = [summary["conditions"][t][metric]["lo"] for t in tags]
        hi = [summary["conditions"][t][metric]["hi"] for t in tags]
        yerr = np.array([[e - l, h - e] for e, l, h in zip(est, lo, hi)]).T
        x = np.arange(len(tags))
        bars = ax.bar(x, est, yerr=yerr, capsize=4, color=colors[: len(tags)], alpha=0.9, ecolor="#222", width=0.72)
        ax.set_xticks(x, [LABEL.get(t, t) for t in tags], fontsize=9)
        ax.set_ylabel(metric.replace("_", " "))
        ax.set_title(title)
        ax.set_ylim(0, max(hi) * 1.18)
        for i, e in enumerate(est):
            ax.text(i, hi[i] + 0.008, f"{e:.3f}", ha="center", va="bottom", fontsize=8)
        # highlight fp as reference line
        if "fp" in tags:
            ax.axhline(summary["conditions"]["fp"][metric]["est"], color="#6b7280", ls="--", lw=0.9, alpha=0.7)
    fig.suptitle("Main conditions vs baselines (mean over calib. seeds; 95% cluster-bootstrap CI)", fontsize=11)
    fig.tight_layout()
    return _save(fig, "conditions_vs_baseline.png")


def ablations(summary) -> Path:
    """Ablation call_exact with CI: mask variants + A8 + FP8 scale fixes."""
    tags = [
        t
        for t in (
            "awq_long_nomask",
            "awq_long_masked",
            "awq_long_masked_strict",
            "awq_long_masked_matched",
            "awq_long_template_only",
            "awq_long_nomask_a8",
            "awq_long_masked_a8",
            "rtn_fp8",
            "rtn_fp8_channel",
        )
        if t in summary["conditions"]
    ]
    fig, ax = plt.subplots(figsize=(12, 4.5))
    est = [summary["conditions"][t]["call_exact"]["est"] for t in tags]
    lo = [summary["conditions"][t]["call_exact"]["lo"] for t in tags]
    hi = [summary["conditions"][t]["call_exact"]["hi"] for t in tags]
    yerr = np.array([[e - l, h - e] for e, l, h in zip(est, lo, hi)]).T
    x = np.arange(len(tags))
    # color: green=nomask family, red=masked family, purple=fp8
    cmap = []
    for t in tags:
        if "fp8" in t:
            cmap.append("#7c3aed")
        elif "masked" in t:
            cmap.append("#ef4444")
        else:
            cmap.append("#10b981")
    ax.bar(x, est, yerr=yerr, capsize=3.5, color=cmap, alpha=0.88, ecolor="#222", width=0.75)
    ax.set_xticks(x, [LABEL.get(t, t) for t in tags], fontsize=8)
    ax.set_ylabel("call_exact")
    ax.set_title("Ablations: mask variants, matched budget, A8, FP8 group scales (call_exact ± 95% CI)")
    ax.set_ylim(0, max(hi) * 1.2)
    # reference: awq_long_nomask
    if "awq_long_nomask" in summary["conditions"]:
        ref = summary["conditions"]["awq_long_nomask"]["call_exact"]["est"]
        ax.axhline(ref, color="#10b981", ls="--", lw=1.0, alpha=0.8, label=f"nomask = {ref:.3f}")
        ax.legend(loc="upper right", fontsize=8)
    for i, e in enumerate(est):
        ax.text(i, hi[i] + 0.01, f"{e:.3f}", ha="center", va="bottom", fontsize=7.5)
    fig.tight_layout()
    return _save(fig, "ablations.png")


def paired_seed_deltas(summary) -> Path:
    """Paired call_exact deltas: forest (CI) + per-seed point deltas for key contrasts."""
    key_pairs = [
        ("awq_long_masked - awq_long_nomask", "masked − nomask"),
        ("awq_long_masked - awq_short", "masked − short"),
        ("awq_long_nomask - awq_short", "nomask − short"),
        ("awq_long_masked_strict - awq_long_masked", "strict − masked"),
        ("awq_long_template_only - awq_long_nomask", "template-only − nomask"),
        ("awq_short - rtn", "short − RTN"),
        ("awq_long_nomask - rtn", "nomask − RTN"),
        ("rtn - fp", "RTN − fp32"),
    ]
    pairs = summary["pairs"]
    present = [(k, lab) for k, lab in key_pairs if k in pairs]

    runs = S.load()
    fig, axes = plt.subplots(1, 2, figsize=(12.5, 5.0), gridspec_kw={"width_ratios": [1.15, 1]})

    # Left: forest of paired CIs
    ax = axes[0]
    for i, (k, lab) in enumerate(present):
        r = pairs[k]["call_exact"]
        significant = r["lo"] > 0 or r["hi"] < 0
        color = "#111" if significant else "#9ca3af"
        ax.errorbar(
            r["est"],
            i,
            xerr=[[r["est"] - r["lo"]], [r["hi"] - r["est"]]],
            fmt="o",
            color=color,
            capsize=3,
            markersize=6,
        )
        ax.text(r["hi"] + 0.005, i, f"{r['est']:+.3f}", va="center", fontsize=8, color=color)
    ax.axvline(0, color="#ef4444", lw=1.0)
    ax.set_yticks(range(len(present)), [lab for _, lab in present], fontsize=9)
    ax.invert_yaxis()
    ax.set_xlabel("Δ call_exact (paired, 95% cluster-bootstrap CI)")
    ax.set_title("Headline paired deltas")

    # Right: per-seed point deltas for the three core AWQ contrasts
    ax = axes[1]
    core = [
        ("awq_long_masked", "awq_long_nomask", "masked−nomask", "#ef4444"),
        ("awq_long_nomask", "awq_short", "nomask−short", "#10b981"),
        ("awq_long_masked", "awq_short", "masked−short", "#3b82f6"),
        ("awq_long_masked_strict", "awq_long_masked", "strict−masked", "#f59e0b"),
    ]
    block, fn = S.METRICS["call_exact"]
    offset = np.linspace(-0.18, 0.18, 3)
    for j, (a, b, lab, color) in enumerate(core):
        if a not in runs or b not in runs:
            continue
        seeds = sorted(set(runs[a]) & set(runs[b]))
        deltas = []
        for si, s in enumerate(seeds):
            va = S.stat(runs[a][s][block], fn)
            vb = S.stat(runs[b][s][block], fn)
            d = va - vb
            deltas.append(d)
            ax.scatter(d, j + (offset[si] if len(seeds) == 3 else 0), color=color, s=55, zorder=3, edgecolors="k", lw=0.4)
        if deltas:
            ax.scatter(np.mean(deltas), j, marker="D", color=color, s=70, zorder=4, edgecolors="k", lw=0.6, label=lab if j == 0 else None)
            # mean diamond already; add small label
            ax.text(np.mean(deltas), j - 0.28, f"μ={np.mean(deltas):+.3f}", ha="center", fontsize=7.5, color=color)
    ax.axvline(0, color="#ef4444", lw=1.0)
    ax.set_yticks(range(len(core)), [c[2] for c in core], fontsize=9)
    ax.invert_yaxis()
    ax.set_xlabel("Δ call_exact (per calibration seed; ◆ = mean)")
    ax.set_title("Per-seed paired deltas")
    ax.set_xlim(-0.15, 0.15)

    fig.suptitle("Masking looks negative at this scale: masked − nomask is ≤ 0 across seeds; CI crosses or near zero", fontsize=10.5)
    fig.tight_layout()
    return _save(fig, "paired_seed_deltas.png")


def error_categories() -> Path | None:
    """Stacked free-gen error shares from heldout results (if present)."""
    ho = ROOT / "results/heldout"
    if not ho.exists() or not any(ho.glob("*.json")):
        return None
    from collections import Counter, defaultdict

    from .heldout import CATEGORIES

    raw = defaultdict(dict)
    for f in sorted(ho.glob("*.json")):
        tag, s = f.stem.rsplit("__s", 1)
        raw[tag][int(s)] = json.loads(f.read_text())
    tags = [t for t in S.ORDER if t in raw]
    fig, ax = plt.subplots(1, 2, figsize=(13, 4.6), sharey=True)
    cmap = plt.get_cmap("tab10")
    for i, split in enumerate(("heldout", "indist")):
        bottom = np.zeros(len(tags))
        for k, cat in enumerate(CATEGORIES):
            shares = []
            for t in tags:
                ps = [p for d in raw[t].values() for p in d["generation"][split]]
                c = Counter(p["category"] for p in ps)
                shares.append(c.get(cat, 0) / max(len(ps), 1))
            v = np.array(shares)
            ax[i].bar([LABEL.get(t, t).replace("\n", " ") for t in tags], v, bottom=bottom, label=cat, color="#4c9a2a" if cat == "correct" else cmap(k))
            bottom += v
        ax[i].set_title({"heldout": "Held-out tools", "indist": "In-distribution tools"}[split] + " — free generation")
        ax[i].tick_params(axis="x", rotation=20)
    ax[0].set_ylabel("share of prompts")
    ax[1].legend(bbox_to_anchor=(1.01, 1), loc="upper left", fontsize=8)
    fig.suptitle("Free-generation error categories (summed over calibration seeds)", fontsize=11)
    fig.tight_layout()
    return _save(fig, "error_categories.png")


def main():
    sj = ROOT / "results/summary.json"
    if not sj.exists():
        raise SystemExit("results/summary.json missing — run `uv run python -m src.summarize` first")
    summary = json.loads(sj.read_text())
    made = [
        conditions_vs_baseline(summary),
        ablations(summary),
        paired_seed_deltas(summary),
    ]
    ec = error_categories()
    if ec:
        made.append(ec)
    # Also keep / refresh the report forest if summary exists (optional mirror)
    print("wrote:", ", ".join(p.name for p in made))
    for p in made:
        print(" ", p)


if __name__ == "__main__":
    main()
